#!/usr/bin/env python3
"""Read-only outreach adapter; copy authoritative journey functions, never edit masters."""
import json
import re
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'clubfinder.html').read_text()
def span(start, end):
    i = source.index(start)
    return source[i:source.index(end, i + len(start))].strip()
def data(name):
    i = source.index('const ' + name + '=') + len('const ' + name + '=')
    return json.JSONDecoder().raw_decode(source[i:])[0]
functions = [
    span('function norm(', 'function findGround('),
    span('function candidateClubByName(', 'function candidateIsActive('),
    span('function liveLookup(', 'function liveResultHistory('),
    span('function resultNeedsReplay(', 'function replayVenue('),
    span('function canonicalClubKey(', 'function groundByClubName('),
    span('function resultSortValue(', 'function tinFoilJourneyForRender('),
]
# Functions above are verbatim; a per-read cache avoids recomputing identical club histories.
text = '/* Generated by updater/build_club_campaign_engine.py from the production journey engine. */\n'
for name in ['ELIGIBLE', 'EPR_RESULTS_BY_TIE', 'CURRENT_RESULT_OVERRIDES']:
    text += 'const ' + name + '=' + json.dumps(data(name), separators=(',', ':')) + ';\n'
text += 'export function campaignEngine(LIVE_COMPETITION_DATA){\n' + '\n'.join(functions)
text += '''
 const originalHistory=historicalResultsForClub,cache=new Map();
 historicalResultsForClub=function(club){
  const key=JSON.stringify([club.name,club.entry_round,club.fixture?.number]);
  if(!cache.has(key))cache.set(key,originalHistory(club));
  return cache.get(key);
 };
 return {origins:ELIGIBLE,buildJourney,sameClubIdentity,canonicalResultWinner,resultNeedsReplay,
  resultCandidates:[...Object.values(EPR_RESULTS_BY_TIE),...Object.values(CURRENT_RESULT_OVERRIDES),...ELIGIBLE.map(o=>o.fixture?.result).filter(Boolean),...Object.values(LIVE_COMPETITION_DATA.result_history||{}).flat(),...Object.values(LIVE_COMPETITION_DATA.results||{})]};
}
'''
target = ROOT / 'beta/club-details-engine.mjs'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != text:
        sys.exit('Club Campaign adapter differs from authoritative engine; regenerate it.')
    print('PASS: outreach uses unchanged authoritative origin list and journey functions.')
else:
    target.write_text(text)
