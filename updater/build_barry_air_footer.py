#!/usr/bin/env python3
"""Keep Barry Air's footer copy and destinations aligned with public Clubfinder."""
import ast
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'beta/clubfinder-beta.html').read_text()

def literal(section, pattern):
    match = re.search(pattern, section)
    if not match:
        raise SystemExit('Public footer source could not be extracted')
    return ast.literal_eval(match[1])

about = literal(source.split('function tffcAboutUs(){', 1)[1].split('function tinFoilPrivacyNotice(){', 1)[0], r'overlay\.innerHTML=("(?:\\.|[^"\\])*");')
privacy = literal(source.split('function tinFoilPrivacyNotice(){', 1)[1].split('function tinFoilConfirm(', 1)[0], r"overlay\.innerHTML=('(?:\\.|[^'\\])*');")
admin = literal(source.split('function tinFoilSupportLinksHtml(){', 1)[1].split('\n}', 1)[0], r"return ('(?:\\.|[^'\\])*');")
values = {
    'adminHtml': admin,
    'aboutBody': re.search(r'<div class="tffc-about-story">(.*?)</div>', about)[1],
    'privacyBody': re.search(r'id="tinFoilPrivacyMessage"[^>]*>(.*?)</div>', privacy)[1],
    'supportURL': re.search(r'https://buy\.stripe\.com/[A-Za-z0-9]+', source)[0],
}
output = '// Generated by updater/build_barry_air_footer.py from public Clubfinder.\n'
output += '\n'.join('export const ' + name + '=' + json.dumps(value, ensure_ascii=False) + ';' for name, value in values.items()) + '\n'
path = ROOT / 'beta/barry-air/footer-content.mjs'
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != output:
        raise SystemExit('Barry Air footer is stale: run updater/build_barry_air_footer.py')
    print('PASS: Barry Air footer uses the public support destination and information copy.')
else:
    path.write_text(output)
    print(path.relative_to(ROOT))
